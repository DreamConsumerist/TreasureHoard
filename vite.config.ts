/// <reference types="vitest/config" />
import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'
import type { Plugin } from 'vite'
import { VitePWA } from 'vite-plugin-pwa'

// Writes Netlify's SPA fallback rule into dist/_redirects, during production
// builds only. In production, Netlify serves index.html for any path without
// a matching file, and React Router takes over in the browser.
//
// Why not public/_redirects or netlify.toml: `netlify dev` reads those rules
// too, and rewrote Vite's dev-only module requests (/src/main.tsx,
// /@vite/client) to index.html, which broke the app locally. In development,
// Vite's own server already does the SPA fallback.
function netlifySpaFallback(): Plugin {
  return {
    name: 'netlify-spa-fallback',
    apply: 'build',
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: '_redirects',
        source: '/*  /index.html  200\n',
      })
    },
  }
}

// Installable app (PWA): writes manifest.webmanifest and a service worker
// (sw.js, generated by Workbox) into dist/ during production builds.
//
// The service worker precaches only the app's own built files, so the app
// opens fast and still loads with no connection. It never caches data:
// /api/* and Netlify functions are excluded from the page fallback, and
// there are no runtime caching rules, so those requests always go to the
// network. Off in development (the plugin's default).
//
// registerType 'prompt': a new deploy waits for you to press Reload
// (src/components/UpdateBar.tsx) instead of reloading mid-entry.
const pwa = VitePWA({
  registerType: 'prompt',
  injectRegister: false, // registered by UpdateBar via virtual:pwa-register/react
  manifest: {
    name: 'TreasureHoard',
    short_name: 'TreasureHoard',
    description: 'Personal ledger and collection tracker',
    start_url: '/',
    scope: '/',
    display: 'standalone',
    background_color: '#18181b',
    theme_color: '#18181b',
    icons: [
      { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
      { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
      { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
      {
        src: 'maskable-icon-512x512.png',
        sizes: '512x512',
        type: 'image/png',
        purpose: 'maskable',
      },
    ],
  },
  workbox: {
    globPatterns: ['**/*.{js,css,html,svg,png,ico,webmanifest}'],
    navigateFallback: '/index.html',
    navigateFallbackDenylist: [/^\/api\//, /^\/\.netlify\//],
    cleanupOutdatedCaches: true,
  },
})

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), tailwindcss(), netlifySpaFallback(), pwa],
  test: {
    include: ['tests/**/*.test.ts'],
    environment: 'node',
  },
})
